export function getPackageIconComponent(name?: string | null): LucideIcon | null {
  if (!name || !isSupportedPackageIcon(name)) return null;
  return ICON_COMPONENTS[name] || null;
}

export function PackageIcon({
  name,
  className,
}: {
  name?: string | null;
  className?: string;
}) {
  const Icon = getPackageIconComponent(name);
  return Icon ? <Icon className={className} aria-hidden="true" /> : null;
}
